//! Independent-reference regression tests.
//!
//! A golden generated from our own output only ever catches *drift* — it freezes whatever
//! we did on day one, right or wrong. These come from OpenCV instead: the same YuNet ONNX
//! decoded by OpenCV's `FaceDetectorYN`, and the similarity transform estimated by
//! OpenCV's own estimator. Regenerate with `tools/gen-goldens.py`.
//!
//! That distinction matters most for alignment. wiki/05 calls a silently-drifting
//! alignment "the classic bug in every reimplementation of this pipeline" — it throws no
//! error and logs nothing, it just makes every embedding slightly wrong. Our own analytic
//! tests prove the arithmetic is self-consistent; only an independent implementation can
//! say the *conventions* are right.
//!
//! Two files, split by whether they contain biometrics:
//!
//! * `align_golden.txt` + `align_golden_chip.bin` — synthetic, committed, always runs.
//! * `detect_golden.txt` — derived from real faces, gitignored, skips loudly when absent.

mod common;

use std::collections::HashMap;
use std::path::PathBuf;

use faciolock_vision::align::{self, Similarity, CHIP_SIZE, REFERENCE_POINTS};
use faciolock_vision::config::DetectConfig;
use faciolock_vision::detect::LANDMARKS;
use faciolock_vision::{Detector, Frame};

fn testdata() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("testdata")
}

/// The synthetic source image, generated by integer arithmetic so Rust and Python produce
/// byte-identical input without shipping a picture.
///
/// A checkerboard with unequal block sizes — see `tools/gen-goldens.py` for why the block
/// geometry is what it is. Must stay in step with that file.
fn pattern(w: usize, h: usize) -> Vec<u8> {
    let mut px = vec![0u8; w * h];
    for y in 0..h {
        for x in 0..w {
            px[y * w + x] = if (x / 16 + y / 24).is_multiple_of(2) { 40 } else { 215 };
        }
    }
    px
}

struct AlignGolden {
    width: usize,
    height: usize,
    landmarks: [(f32, f32); LANDMARKS],
    reference: [(f32, f32); LANDMARKS],
    transform: [f64; 6],
    chip: Vec<u8>,
}

fn load_align_golden() -> Option<AlignGolden> {
    let dir = testdata();
    let text = std::fs::read_to_string(dir.join("align_golden.txt")).ok()?;
    let chip = std::fs::read(dir.join("align_golden_chip.bin")).ok()?;

    let (mut width, mut height) = (0usize, 0usize);
    let mut landmarks = Vec::new();
    let mut reference = Vec::new();
    let mut transform = [0f64; 6];

    for line in text.lines() {
        let mut f = line.split_whitespace();
        match f.next() {
            Some("pattern") => {
                width = f.next()?.parse().ok()?;
                height = f.next()?.parse().ok()?;
            }
            Some("landmark") => {
                landmarks.push((f.next()?.parse().ok()?, f.next()?.parse().ok()?))
            }
            Some("reference") => {
                reference.push((f.next()?.parse().ok()?, f.next()?.parse().ok()?))
            }
            Some("transform") => {
                for slot in &mut transform {
                    *slot = f.next()?.parse().ok()?;
                }
            }
            _ => {}
        }
    }

    Some(AlignGolden {
        width,
        height,
        landmarks: landmarks.try_into().ok()?,
        reference: reference.try_into().ok()?,
        transform,
        chip,
    })
}

/// **The conventions check.** Our reference points, landmark order and transform direction
/// must be the ones ArcFace-family embedders were trained against, and only an independent
/// implementation can say so.
#[test]
fn alignment_reference_points_match_opencv() {
    let Some(g) = load_align_golden() else {
        common::skip("alignment golden", &testdata().join("align_golden.txt"));
        return;
    };

    // The constants themselves, before any arithmetic runs on them.
    for (i, (rx, ry)) in REFERENCE_POINTS.iter().enumerate() {
        assert!(
            (rx - g.reference[i].0).abs() < 1e-4 && (ry - g.reference[i].1).abs() < 1e-4,
            "reference point {i} is ({rx},{ry}) here and {:?} in the golden",
            g.reference[i]
        );
    }

    let ours = align::estimate_similarity(&g.landmarks, &REFERENCE_POINTS)
        .expect("well-conditioned landmarks");

    // OpenCV returns a row-major 2x3 [[a, -b, tx], [b, a, ty]].
    let (want_a, want_nb, want_tx) = (g.transform[0], g.transform[1], g.transform[2]);
    let (want_b, want_ty) = (g.transform[3], g.transform[5]);
    assert!(
        (want_nb + want_b).abs() < 1e-6,
        "the golden is not a similarity transform: {:?}",
        g.transform
    );

    assert!(
        (ours.a as f64 - want_a).abs() < 1e-4,
        "scale*cos: ours {} vs OpenCV {want_a}",
        ours.a
    );
    assert!(
        (ours.b as f64 - want_b).abs() < 1e-4,
        "scale*sin: ours {} vs OpenCV {want_b}",
        ours.b
    );
    assert!(
        (ours.tx as f64 - want_tx).abs() < 1e-2,
        "tx: ours {} vs OpenCV {want_tx}",
        ours.tx
    );
    assert!(
        (ours.ty as f64 - want_ty).abs() < 1e-2,
        "ty: ours {} vs OpenCV {want_ty}",
        ours.ty
    );
}

/// The warp itself, pixels against pixels.
///
/// Not byte-exact, and it cannot be: OpenCV's `INTER_LINEAR` uses fixed-point interpolation
/// tables with 5 bits of fractional precision, ours uses `f32`. A few units of disagreement
/// per pixel is the expected floor. What this catches is the failure that matters —
/// inverting the transform the wrong way, sampling at corners instead of centres, or
/// transposing the chip — all of which produce wholesale differences, not rounding.
#[test]
fn aligned_chip_matches_opencvs_warp() {
    let Some(g) = load_align_golden() else {
        common::skip("alignment golden", &testdata().join("align_golden.txt"));
        return;
    };
    assert_eq!(g.chip.len(), CHIP_SIZE * CHIP_SIZE, "golden chip is the wrong size");

    let px = pattern(g.width, g.height);
    let frame = Frame::new(&px, g.width, g.height).expect("pattern is well formed");
    let ours = align::align(&frame, &g.landmarks).expect("alignment succeeds");

    let n = g.chip.len() as f64;
    let diffs: Vec<u32> = ours
        .pixels
        .iter()
        .zip(&g.chip)
        .map(|(a, b)| a.abs_diff(*b) as u32)
        .collect();
    let mean = diffs.iter().sum::<u32>() as f64 / n;
    let max = diffs.iter().copied().max().unwrap_or(0);
    let within_2 = diffs.iter().filter(|&&d| d <= 2).count() as f64 / n;

    eprintln!(
        "\naligned chip vs OpenCV warpAffine\n  mean |diff| {mean:.3}\n  max  |diff| {max}\n  \
         within 2 levels {:.1}%",
        within_2 * 100.0
    );

    // These are tight because the two warps genuinely agree: mean 0.000, max 1, 100%
    // within 2 levels. The only residual is OpenCV's fixed-point bilinear rounding
    // against our f32.
    //
    // They were once loose, to accommodate a mean of 3.2 that was assumed to be
    // interpolation noise. It was not — it was a half-pixel sampling offset, a systematic
    // ~0.21 px shift of every point. **A tolerance wide enough to swallow a real defect is
    // not a tolerance.** If this ever needs loosening again, find out why first.
    assert!(mean < 0.5, "mean |diff| {mean} — this is not the same warp");
    assert!(max <= 2, "max |diff| {max} — larger than interpolation rounding can explain");
    assert!(within_2 > 0.999, "only {:.1}% of pixels within 2 levels", within_2 * 100.0);
}

struct GoldenFace {
    bounds: [f64; 4],
    score: f64,
    landmarks: [(f64, f64); LANDMARKS],
}

fn load_detect_golden() -> Option<HashMap<String, Vec<GoldenFace>>> {
    let text = std::fs::read_to_string(testdata().join("detect_golden.txt")).ok()?;
    let mut out: HashMap<String, Vec<GoldenFace>> = HashMap::new();
    let mut current = String::new();

    for line in text.lines() {
        let mut f = line.split_whitespace();
        match f.next() {
            Some("capture") => {
                current = f.next()?.to_string();
                out.entry(current.clone()).or_default();
            }
            Some("face") => {
                let v: Vec<f64> = f.filter_map(|t| t.parse().ok()).collect();
                if v.len() < 15 {
                    continue;
                }
                let mut lms = [(0.0f64, 0.0f64); LANDMARKS];
                for (i, lm) in lms.iter_mut().enumerate() {
                    *lm = (v[5 + 2 * i], v[6 + 2 * i]);
                }
                out.entry(current.clone()).or_default().push(GoldenFace {
                    bounds: [v[0], v[1], v[2], v[3]],
                    score: v[4],
                    landmarks: lms,
                });
            }
            _ => {}
        }
    }
    Some(out)
}

/// Our 12-tensor YuNet decode against OpenCV's, on the real corpus.
///
/// The decode has several places to be quietly wrong — `exp` versus linear box deltas,
/// `sqrt(cls * obj)` versus either alone, grid-relative landmark offsets, the stride
/// mapping. Every one of those produces *plausible* boxes, which is exactly why an
/// independent decode of the same file is worth having.
#[test]
fn detection_matches_opencvs_own_decode() {
    let Some(golden) = load_detect_golden() else {
        common::skip("detection golden", &testdata().join("detect_golden.txt"));
        return;
    };
    let yunet = common::yunet();
    if !yunet.exists() {
        common::skip("YuNet model", &yunet);
        return;
    }
    let captures = common::captures();
    if captures.is_empty() {
        return;
    }

    let cfg = DetectConfig::default();
    let det = Detector::load(&yunet, &cfg).expect("model loads");

    eprintln!(
        "\nour decode vs OpenCV's, same ONNX, {}x{}\n{:<26} {:>7} {:>7} {:>9} {:>12}",
        cfg.input_size, cfg.input_size, "capture", "ours", "opencv", "box IoU", "landmark px"
    );

    let mut compared = 0;
    for cap in &captures {
        // Keyed by stem, not label. Two takes of the same scene share a label, and a
        // lookup by label silently returned the *other* take's golden — a different
        // session, a different pose, and a comparison that meant nothing. Same shape as
        // B6: a name that looks stable and resolves to the wrong object.
        let Some(want) = golden.get(&cap.stem) else { continue };

        // Same frame-selection rule as the generator: brightest past AGC settle.
        let idx = (5..20.min(cap.frame_count()))
            .max_by(|&a, &b| {
                let m = |i: usize| {
                    let f = cap.frame(i);
                    f.iter().map(|&p| u64::from(p)).sum::<u64>() as f64 / f.len() as f64
                };
                m(a).partial_cmp(&m(b)).unwrap_or(std::cmp::Ordering::Equal)
            })
            .unwrap_or(0);
        let frame = Frame::new(cap.frame(idx), cap.width, cap.height).expect("geometry");
        let ours = det.detect(&frame).expect("inference runs");

        // The classification must agree exactly: a face is there or it is not.
        assert_eq!(
            ours.is_empty(),
            want.is_empty(),
            "{}: we found {} face(s), OpenCV found {}",
            cap.label,
            ours.len(),
            want.len()
        );
        compared += 1;

        let (Some(a), Some(b)) = (ours.first(), want.first()) else {
            eprintln!("{:<26} {:>7} {:>7}", cap.label, ours.len(), want.len());
            continue;
        };

        let gold_rect = faciolock_vision::Rect {
            x: b.bounds[0] as f32,
            y: b.bounds[1] as f32,
            w: b.bounds[2] as f32,
            h: b.bounds[3] as f32,
        };
        let iou = a.bounds.iou(&gold_rect);
        let worst_lm = a
            .landmarks
            .iter()
            .zip(&b.landmarks)
            .map(|((ax, ay), (bx, by))| {
                ((*ax as f64 - bx).powi(2) + (*ay as f64 - by).powi(2)).sqrt()
            })
            .fold(0.0f64, f64::max);

        eprintln!(
            "{:<26} {:>7} {:>7} {iou:>9.3} {worst_lm:>12.2}",
            cap.label,
            ours.len(),
            want.len()
        );

        // Tolerances are loose on purpose. The two sides letterbox with different resize
        // implementations, so a couple of pixels of disagreement is the floor. A wrong
        // decode does not land a couple of pixels away — it lands somewhere else entirely.
        assert!(iou > 0.8, "{}: box IoU {iou:.3} against OpenCV", cap.label);
        assert!(
            worst_lm < 8.0,
            "{}: worst landmark {worst_lm:.2} px from OpenCV's",
            cap.label
        );
        assert!(
            (a.score as f64 - b.score).abs() < 0.15,
            "{}: score {} vs OpenCV {}",
            cap.label,
            a.score,
            b.score
        );
    }

    assert!(compared > 0, "no captures had a golden to compare against");
}

/// The estimator must be the least-squares fit, not something that merely happens to be
/// close. Residual against OpenCV's own, on the golden landmarks.
#[test]
fn our_transform_fits_at_least_as_well_as_opencvs() {
    let Some(g) = load_align_golden() else {
        common::skip("alignment golden", &testdata().join("align_golden.txt"));
        return;
    };

    let residual = |s: &Similarity| -> f64 {
        g.landmarks
            .iter()
            .zip(&REFERENCE_POINTS)
            .map(|((lx, ly), (rx, ry))| {
                let (gx, gy) = s.apply(*lx, *ly);
                ((gx - rx).powi(2) + (gy - ry).powi(2)) as f64
            })
            .sum()
    };

    let ours = align::estimate_similarity(&g.landmarks, &REFERENCE_POINTS).unwrap();
    let theirs = Similarity {
        a: g.transform[0] as f32,
        b: g.transform[3] as f32,
        tx: g.transform[2] as f32,
        ty: g.transform[5] as f32,
    };

    let (r_ours, r_theirs) = (residual(&ours), residual(&theirs));
    eprintln!("\nsum of squared residuals\n  ours   {r_ours:.6}\n  opencv {r_theirs:.6}");
    assert!(
        r_ours <= r_theirs + 1e-3,
        "ours fits worse than OpenCV's: {r_ours} vs {r_theirs}"
    );
}
